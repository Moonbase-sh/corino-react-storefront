'use client'

import { ActivationMethod, type License, useInventory } from '@moonbase.sh/react'
import { useState } from 'react'
import { DeviceTokenInput } from './DeviceTokenInput'
import { ActivationProductCard } from './ProductCard'

/** Offline activation: upload the machine file a device made, get a license file back for it. */
export function ManualActivation() {
  const { activateProduct } = useInventory()

  const [step, setStep] = useState<'input' | 'uploading' | 'done'>('input')
  const [error, setError] = useState<Error | null>(null)
  const [result, setResult] = useState<{ license: License, url: string } | null>(null)

  async function handleToken(token: string) {
    setError(null)
    setStep('uploading')
    try {
      setResult(await activateProduct(token, ActivationMethod.Offline))
      setStep('done')
    }
    catch (err) {
      setError(err instanceof Error ? err : new Error(String(err)))
      setStep('input')
    }
  }

  function reset() {
    setError(null)
    setResult(null)
    setStep('input')
  }

  return (
    <div className="manual-activation">
      <p className="hint">
        Upload your machine file here to get a license file for activating offline devices.
        The machine file is generated by the plugin running on the device.
      </p>

      {step === 'input' && <DeviceTokenInput error={error} onToken={handleToken} onError={setError} />}

      {step === 'uploading' && (
        <div className="activation-loader"><p>Generating license…</p></div>
      )}

      {step === 'done' && result && (
        <div className="manual-activation-result">
          <h3>Success</h3>
          <p>Your license is ready to download.</p>
          {result.license.product && (
            <ActivationProductCard
              product={result.license.product}
              description={(
                <p className="hint">
                  {`${result.license.activeNumberOfActivations} of ${result.license.maxNumberOfActivations} devices activated`}
                </p>
              )}
            >
              <a className="submit" href={result.url} target="_blank" rel="noopener" download="license-file.mb">
                Download license file
              </a>
            </ActivationProductCard>
          )}
          <button type="button" className="logout" onClick={reset}>Activate another device</button>
        </div>
      )}
    </div>
  )
}
